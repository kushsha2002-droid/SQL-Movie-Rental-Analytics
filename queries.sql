-- MovieCo analysis queries (SQL Server / T-SQL)

-- 1. Above-average rentals: transactions with more videos AND a higher total fee
--    than the average rental transaction.
SELECT
    R.RENT_NUM,
    R.RENT_DATE,
    R.MEM_NUM,
    COUNT(DR.VID_NUM)  AS NUM_VIDEOS_RENTED,
    SUM(DR.DETAIL_FEE) AS TOTAL_RENTAL_FEE,
    AVG(DR.DETAIL_FEE) AS AVG_FEE_PER_VIDEO
FROM RENTAL R
JOIN DETAILRENTAL DR ON R.RENT_NUM = DR.RENT_NUM
GROUP BY R.RENT_NUM, R.RENT_DATE, R.MEM_NUM
HAVING
    COUNT(DR.VID_NUM) > (
        SELECT AVG(CAST(VID_COUNT AS FLOAT))
        FROM (
            SELECT COUNT(VID_NUM) AS VID_COUNT
            FROM DETAILRENTAL
            GROUP BY RENT_NUM
        ) AS AVG_VIDEOS
    )
    AND SUM(DR.DETAIL_FEE) > (
        SELECT AVG(TOTAL_FEE)
        FROM (
            SELECT SUM(DETAIL_FEE) AS TOTAL_FEE
            FROM DETAILRENTAL
            GROUP BY RENT_NUM
        ) AS AVG_FEES
    )
ORDER BY TOTAL_RENTAL_FEE DESC;

-- 2. Longest rental duration (returned videos only), using a CTE.
WITH RENTAL_DURATION AS (
    SELECT
        M.MEM_NUM,
        M.MEM_LNAME,
        M.MEM_FNAME,
        MV.MOVIE_TITLE,
        MV.MOVIE_GENRE,
        R.RENT_NUM,
        R.RENT_DATE,
        DR.DETAIL_RETURNDATE,
        DATEDIFF(DAY, R.RENT_DATE, DR.DETAIL_RETURNDATE) AS RENTAL_DURATION_DAYS
    FROM MEMBERSHIP M
    JOIN RENTAL R        ON M.MEM_NUM = R.MEM_NUM
    JOIN DETAILRENTAL DR ON R.RENT_NUM = DR.RENT_NUM
    JOIN VIDEO V         ON DR.VID_NUM = V.VID_NUM
    JOIN MOVIE MV        ON V.MOVIE_NUM = MV.MOVIE_NUM
    WHERE DR.DETAIL_RETURNDATE IS NOT NULL
)
SELECT *
FROM RENTAL_DURATION
WHERE RENTAL_DURATION_DAYS = (SELECT MAX(RENTAL_DURATION_DAYS) FROM RENTAL_DURATION)
ORDER BY MEM_LNAME, MEM_FNAME, MOVIE_TITLE;

-- 3. Members whose rental income (fees + late fees) is above the per-member average.
WITH MEMBER_INCOME AS (
    SELECT
        M.MEM_NUM,
        M.MEM_LNAME,
        M.MEM_FNAME,
        SUM(DR.DETAIL_FEE + ISNULL(DR.DETAIL_DAILYLATEFEE, 0)) AS RENTAL_INCOME
    FROM MEMBERSHIP M
    JOIN RENTAL R        ON M.MEM_NUM = R.MEM_NUM
    JOIN DETAILRENTAL DR ON R.RENT_NUM = DR.RENT_NUM
    GROUP BY M.MEM_NUM, M.MEM_LNAME, M.MEM_FNAME
)
SELECT *
FROM MEMBER_INCOME
WHERE RENTAL_INCOME > (SELECT AVG(RENTAL_INCOME) FROM MEMBER_INCOME)
ORDER BY RENTAL_INCOME DESC;

-- 4. Top 5 genres by rental income (pricing-strategy view).
SELECT TOP 5
    MV.MOVIE_GENRE,
    SUM(DR.DETAIL_FEE)  AS RENTAL_INCOME,
    COUNT(DR.VID_NUM)   AS NUMBER_OF_RENTALS,
    AVG(DR.DETAIL_FEE)  AS AVG_FEE_PER_RENTAL
FROM MOVIE MV
JOIN VIDEO V         ON MV.MOVIE_NUM = V.MOVIE_NUM
JOIN DETAILRENTAL DR ON V.VID_NUM = DR.VID_NUM
GROUP BY MV.MOVIE_GENRE
ORDER BY RENTAL_INCOME DESC;
