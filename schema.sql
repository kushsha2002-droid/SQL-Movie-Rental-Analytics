-- MovieCo rental database schema (SQL Server / T-SQL)
-- Create tables in dependency order: parents first.

CREATE TABLE PRICE (
    PRICE_CODE         VARCHAR(10) NOT NULL,
    PRICE_DESCRIPTION  VARCHAR(50),
    PRICE_RENTFEE      DECIMAL(8,2),
    PRICE_DAILYLATEFEE DECIMAL(8,2),
    CONSTRAINT PK_PRICE PRIMARY KEY (PRICE_CODE)
);

CREATE TABLE MEMBERSHIP (
    MEM_NUM     INT NOT NULL,
    MEM_FNAME   VARCHAR(30),
    MEM_LNAME   VARCHAR(30),
    MEM_STREET  VARCHAR(50),
    MEM_CITY    VARCHAR(30),
    MEM_STATE   CHAR(2),
    MEM_ZIP     CHAR(10),
    MEM_BALANCE DECIMAL(8,2),
    CONSTRAINT PK_MEMBERSHIP PRIMARY KEY (MEM_NUM)
);

CREATE TABLE MOVIE (
    MOVIE_NUM   INT NOT NULL,
    MOVIE_TITLE VARCHAR(100),
    MOVIE_YEAR  SMALLINT,
    MOVIE_COST  DECIMAL(8,2),
    MOVIE_GENRE VARCHAR(30),
    PRICE_CODE  VARCHAR(10),
    CONSTRAINT PK_MOVIE PRIMARY KEY (MOVIE_NUM),
    CONSTRAINT FK_MOVIE_PRICE FOREIGN KEY (PRICE_CODE) REFERENCES PRICE(PRICE_CODE)
);

CREATE TABLE VIDEO (
    VID_NUM    INT NOT NULL,
    VID_INDATE DATE,
    MOVIE_NUM  INT,
    CONSTRAINT PK_VIDEO PRIMARY KEY (VID_NUM),
    CONSTRAINT FK_VIDEO_MOVIE FOREIGN KEY (MOVIE_NUM) REFERENCES MOVIE(MOVIE_NUM)
);

CREATE TABLE RENTAL (
    RENT_NUM  INT NOT NULL,
    RENT_DATE DATE,
    MEM_NUM   INT,
    CONSTRAINT PK_RENTAL PRIMARY KEY (RENT_NUM),
    CONSTRAINT FK_RENTAL_MEMBERSHIP FOREIGN KEY (MEM_NUM) REFERENCES MEMBERSHIP(MEM_NUM)
);

CREATE TABLE DETAILRENTAL (
    RENT_NUM            INT NOT NULL,
    VID_NUM             INT NOT NULL,
    DETAIL_FEE          DECIMAL(8,2),
    DETAIL_DUEDATE      DATE,
    DETAIL_RETURNDATE   DATE,
    DETAIL_DAILYLATEFEE DECIMAL(8,2),
    CONSTRAINT PK_DETAILRENTAL PRIMARY KEY (RENT_NUM, VID_NUM),
    CONSTRAINT FK_DETAIL_RENTAL FOREIGN KEY (RENT_NUM) REFERENCES RENTAL(RENT_NUM),
    CONSTRAINT FK_DETAIL_VIDEO  FOREIGN KEY (VID_NUM)  REFERENCES VIDEO(VID_NUM)
);
